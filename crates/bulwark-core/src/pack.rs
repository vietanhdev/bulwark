//! Where a content pack — config rules, log rules or log decoders — comes from.
//!
//! A pack is a set of YAML files. On disk it is a folder (the shipped `/usr/share/bulwark/rules`,
//! a user's `--rules-dir`, a custom-rules folder); compiled into a binary it is a static list of
//! `(relative path, text)` pairs, which is what lets `bulwarkctl` run as a single file with no
//! install step. Every loader reads through [`PackSource::files`], so both shapes get exactly the
//! same parsing, validation and error reporting — an embedded pack is not a second code path that
//! could drift from the real one.

use std::path::{Path, PathBuf};
use walkdir::WalkDir;

/// The largest pack file read from disk. A pack folder can be user-supplied (`--rules-dir`, and it
/// is passed into the root pkexec scan), so a multi-GB `*.yaml` must not be able to exhaust memory.
pub const MAX_PACK_FILE_BYTES: u64 = 1024 * 1024;

/// A pack's files: a folder on disk, or files compiled into the binary.
#[derive(Debug, Clone, Copy)]
pub enum PackSource<'a> {
    Dir(&'a Path),
    /// `(path relative to the pack root, YAML text)`, as generated by a build script.
    Embedded(&'a [(&'a str, &'a str)]),
}

impl<'a> From<&'a Path> for PackSource<'a> {
    fn from(p: &'a Path) -> Self {
        PackSource::Dir(p)
    }
}

impl<'a> From<&'a PathBuf> for PackSource<'a> {
    fn from(p: &'a PathBuf) -> Self {
        PackSource::Dir(p.as_path())
    }
}

/// One pack file: the name it is reported under, and its text or why it couldn't be read.
pub struct PackFile {
    pub path: String,
    pub text: Result<String, String>,
}

impl PackSource<'_> {
    /// Every `.yaml`/`.yml` file in the pack, in a stable order. A file that can't be read is
    /// returned with its error rather than dropped, so the loader reports it (architecture doc §8).
    ///
    /// On disk, symlinks are skipped outright: `read_to_string` on one follows it at the OS level,
    /// so a planted `x.yaml -> /etc/shadow` would otherwise be read — possibly as root — and its
    /// content reflected back in a parse-error message.
    pub fn files(&self) -> Vec<PackFile> {
        match self {
            PackSource::Dir(dir) => WalkDir::new(dir)
                .follow_links(false)
                .sort_by_file_name()
                .into_iter()
                .filter_map(Result::ok)
                .filter(|e| !e.path_is_symlink() && is_yaml(e.path()))
                .map(|e| PackFile {
                    path: e.path().display().to_string(),
                    text: read_capped(e.path(), MAX_PACK_FILE_BYTES).map_err(|e| e.to_string()),
                })
                .collect(),
            PackSource::Embedded(files) => files
                .iter()
                .filter(|(path, _)| is_yaml(Path::new(path)))
                .map(|(path, text)| PackFile {
                    path: format!("built-in:{path}"),
                    text: Ok((*text).to_string()),
                })
                .collect(),
        }
    }

    /// How to name this pack to a person: its folder, or "the built-in pack".
    pub fn describe(&self) -> String {
        match self {
            PackSource::Dir(dir) => dir.display().to_string(),
            PackSource::Embedded(_) => "the built-in pack".to_string(),
        }
    }
}

fn is_yaml(path: &Path) -> bool {
    matches!(
        path.extension().and_then(|e| e.to_str()),
        Some("yaml") | Some("yml")
    )
}

/// Reads at most `max` bytes of `path` as UTF-8 (lossy), so an oversized pack file can't be used
/// to exhaust memory. Opens without following a symlink at the final component.
pub(crate) fn read_capped(path: &Path, max: u64) -> std::io::Result<String> {
    use std::io::Read;
    #[cfg(unix)]
    let file = {
        use std::os::unix::fs::OpenOptionsExt;
        std::fs::OpenOptions::new()
            .read(true)
            .custom_flags(libc::O_NOFOLLOW)
            .open(path)?
    };
    #[cfg(not(unix))]
    let file = std::fs::File::open(path)?;
    let mut buf = Vec::new();
    file.take(max).read_to_end(&mut buf)?;
    Ok(String::from_utf8_lossy(&buf).into_owned())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn an_embedded_pack_lists_only_yaml_in_order_given() {
        let files = [
            ("ssh/A.yaml", "id: A"),
            ("README.md", "not a rule"),
            ("net/B.yml", "id: B"),
        ];
        let got = PackSource::Embedded(&files).files();
        let names: Vec<_> = got.iter().map(|f| f.path.as_str()).collect();
        assert_eq!(names, ["built-in:ssh/A.yaml", "built-in:net/B.yml"]);
        assert_eq!(got[0].text.as_deref(), Ok("id: A"));
        assert_eq!(PackSource::Embedded(&files).describe(), "the built-in pack");
    }

    #[test]
    fn a_folder_pack_is_sorted_and_skips_symlinks() {
        let dir = tempfile::tempdir().unwrap();
        std::fs::create_dir(dir.path().join("b")).unwrap();
        std::fs::write(dir.path().join("b/2.yaml"), "x").unwrap();
        std::fs::write(dir.path().join("a.yaml"), "y").unwrap();
        std::fs::write(dir.path().join("notes.txt"), "z").unwrap();
        #[cfg(unix)]
        std::os::unix::fs::symlink("/etc/hostname", dir.path().join("evil.yaml")).unwrap();
        let got = PackSource::Dir(dir.path()).files();
        let names: Vec<String> = got
            .iter()
            .map(|f| {
                Path::new(&f.path)
                    .strip_prefix(dir.path())
                    .unwrap()
                    .display()
                    .to_string()
                    .replace('\\', "/")
            })
            .collect();
        assert_eq!(names, ["a.yaml", "b/2.yaml"]);
    }
}
